use std::path::{Path, PathBuf};

use polyfont_config::PolyfontConfig;
use serde::{Deserialize, Serialize};

use crate::ThemeError;

/// Theme sharing and project-level persistence utilities.
pub struct ThemeShare;

impl ThemeShare {
    /// Format a config as a shareable TOML string with a header comment.
    ///
    /// # Errors
    ///
    /// Returns [`ThemeError::TomlSerialize`] if the config cannot be serialized.
    pub fn format_gist_content(
        config: &PolyfontConfig,
        description: &str,
    ) -> Result<String, ThemeError> {
        let toml_content = toml::to_string_pretty(config)?;
        Ok(format!(
            "# {description}\n#\n# Generated by polyfont theme share\n\n{toml_content}"
        ))
    }

    /// Fetch a polyfont config from a remote URL. Requires the `download` feature.
    ///
    /// # Errors
    ///
    /// Returns [`ThemeError::DownloadDisabled`] if the `download` feature is not
    /// enabled, [`ThemeError::Validation`] on HTTP failure, or
    /// [`ThemeError::Toml`] if the response body is not valid TOML.
    pub fn fetch_from_url(url: &str) -> Result<PolyfontConfig, ThemeError> {
        #[cfg(feature = "download")]
        {
            Self::fetch_from_url_impl(url)
        }
        #[cfg(not(feature = "download"))]
        {
            let _ = url;
            Err(ThemeError::DownloadDisabled)
        }
    }

    /// Save a config to a project's `.polyfont/themes/` directory.
    ///
    /// # Errors
    ///
    /// Returns [`ThemeError::Io`] if directory creation or writing fails, or
    /// [`ThemeError::TomlSerialize`] if the config cannot be serialized.
    pub fn save_to_project(
        config: &PolyfontConfig,
        project_dir: &Path,
    ) -> Result<PathBuf, ThemeError> {
        let default_family = config
            .default
            .as_ref()
            .map(|d| d.family.as_str())
            .unwrap_or("theme");
        let filename = format!("{}.toml", default_family.to_lowercase().replace(' ', "-"));

        let themes_dir = project_dir.join(".polyfont").join("themes");
        std::fs::create_dir_all(&themes_dir)?;

        let path = themes_dir.join(&filename);
        let content = toml::to_string_pretty(config)?;
        std::fs::write(&path, content)?;

        Ok(path)
    }
}

/// An entry in the theme lockfile tracking remote themes.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ThemeLockEntry {
    pub name: String,
    pub url: String,
    pub sha256: String,
    pub applied_at: String,
}

/// Lockfile tracking applied remote themes.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ThemeLockfile {
    pub themes: Vec<ThemeLockEntry>,
}

impl ThemeLockfile {
    pub fn load(path: &Path) -> Result<Self, ThemeError> {
        let content = std::fs::read_to_string(path)?;
        let lockfile: Self = toml::from_str(&content)?;
        Ok(lockfile)
    }

    pub fn save(&self, path: &Path) -> Result<(), ThemeError> {
        let content = toml::to_string_pretty(self)?;
        std::fs::write(path, content)?;
        Ok(())
    }

    pub fn add_theme(&mut self, name: &str, url: &str, sha256: &str) {
        self.themes.push(ThemeLockEntry {
            name: name.to_string(),
            url: url.to_string(),
            sha256: sha256.to_string(),
            applied_at: chrono_now_or_empty(),
        });
    }
}

fn chrono_now_or_empty() -> String {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs().to_string())
        .unwrap_or_default()
}

#[cfg(feature = "download")]
impl ThemeShare {
    fn fetch_from_url_impl(url: &str) -> Result<PolyfontConfig, ThemeError> {
        let response = reqwest::blocking::Client::new()
            .get(url)
            .send()
            .map_err(|e| ThemeError::Io(std::io::Error::other(e.to_string())))?;

        if !response.status().is_success() {
            return Err(ThemeError::Validation(format!(
                "failed to fetch theme from {url}: HTTP {}",
                response.status()
            )));
        }

        let content = response.text().map_err(|e| {
            ThemeError::Io(std::io::Error::other(format!(
                "failed to read response: {e}"
            )))
        })?;

        let config: PolyfontConfig = toml::from_str(&content)?;
        Ok(config)
    }
}

/// Discovers theme files in project directories.
pub struct ThemeDiscovery;

impl ThemeDiscovery {
    /// Find all `.toml` theme files in a project's `.polyfont/themes/` directory.
    pub fn discover_in_project(project_dir: &Path) -> Vec<PathBuf> {
        let themes_dir = project_dir.join(".polyfont").join("themes");
        if !themes_dir.is_dir() {
            return Vec::new();
        }

        let mut results = Vec::new();
        if let Ok(entries) = std::fs::read_dir(&themes_dir) {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.extension().is_some_and(|ext| ext == "toml") {
                    results.push(path);
                }
            }
        }
        results.sort();
        results
    }

    /// List themes from a lockfile.
    pub fn discover_remote(lockfile: &ThemeLockfile) -> Vec<ThemeLockEntry> {
        lockfile.themes.clone()
    }
}

/// An entry in the remote theme registry.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RemoteThemeEntry {
    pub name: String,
    pub author: String,
    pub source: String,
    #[serde(default)]
    pub fonts: Vec<String>,
    #[serde(default)]
    pub scope_count: u32,
    #[serde(default)]
    pub description: String,
}

/// A registry of remotely available themes.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RemoteThemeRegistry {
    pub themes: Vec<RemoteThemeEntry>,
}

impl RemoteThemeRegistry {
    /// The URL of the official polyfont theme registry.
    pub const REGISTRY_URL: &'static str =
        "https://raw.githubusercontent.com/WyattAu/polyfont/main/themes/themes.json";

    /// Create a registry from a JSON string.
    pub fn from_json(json: &str) -> Result<Self, ThemeError> {
        let registry: Self = serde_json::from_str(json)?;
        Ok(registry)
    }

    /// Serialize the registry to JSON.
    pub fn to_json(&self) -> Result<String, ThemeError> {
        Ok(serde_json::to_string_pretty(self)?)
    }

    /// Find a theme by name (case-insensitive).
    #[must_use]
    pub fn find(&self, name: &str) -> Option<&RemoteThemeEntry> {
        self.themes
            .iter()
            .find(|t| t.name.eq_ignore_ascii_case(name))
    }

    /// List all theme names.
    #[must_use]
    pub fn list_names(&self) -> Vec<&str> {
        self.themes.iter().map(|t| t.name.as_str()).collect()
    }
}

