#[cfg(test)]
mod tests {
    use polyfont_config::{DefaultFontConfig, FontConfig, RuleConfig};
    use polyfont_core::{FontStyle, FontWeight};

    use super::*;

    fn sample_config() -> PolyfontConfig {
        PolyfontConfig {
            version: 1,
            default: Some(DefaultFontConfig {
                family: "Fira Code".to_string(),
                fallbacks: vec![],
                weight: FontWeight::default(),
                style: FontStyle::default(),
                size: None,
                axes: vec![],
            }),
            rules: vec![RuleConfig {
                scope: "keyword".to_string(),
                font: FontConfig {
                    family: "Maple Mono".to_string(),
                    fallbacks: vec![],
                    weight: FontWeight::Bold,
                    style: FontStyle::default(),
                    size: None,
                    axes: vec![],
                },
            }],
        }
    }

    #[test]
    fn test_theme_share_produces_toml() {
        let config = sample_config();
        let result = ThemeShare::format_gist_content(&config, "test theme").unwrap();
        assert!(result.starts_with("# test theme"));
        assert!(result.contains("Fira Code"));
        assert!(result.contains("Maple Mono"));

        let toml_body = result
            .lines()
            .filter(|line| !line.starts_with('#'))
            .collect::<Vec<_>>()
            .join("\n");
        let parsed: PolyfontConfig = toml::from_str(&toml_body).unwrap();
        assert_eq!(parsed.version, 1);
        assert_eq!(parsed.rules.len(), 1);
    }

    fn test_dir(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join("polyfont-test").join(name);
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn test_theme_lockfile_roundtrip() {
        let dir = test_dir("lockfile_roundtrip");
        let path = dir.join("theme.lock");

        let mut lockfile = ThemeLockfile { themes: vec![] };
        lockfile.add_theme("dark", "https://example.com/dark.toml", "abc123");
        lockfile.add_theme("light", "https://example.com/light.toml", "def456");

        lockfile.save(&path).unwrap();
        let loaded = ThemeLockfile::load(&path).unwrap();

        assert_eq!(loaded.themes.len(), 2);
        assert_eq!(loaded.themes[0].name, "dark");
        assert_eq!(loaded.themes[0].url, "https://example.com/dark.toml");
        assert_eq!(loaded.themes[0].sha256, "abc123");
        assert_eq!(loaded.themes[1].name, "light");
    }

    #[test]
    fn test_theme_discovery_empty_dir() {
        let dir = test_dir("discovery_empty");
        let found = ThemeDiscovery::discover_in_project(&dir);
        assert!(found.is_empty());
    }

    #[test]
    fn test_save_to_project_creates_dir() {
        let dir = test_dir("save_to_project");
        let project = dir.join("project");
        let config = sample_config();

        let result = ThemeShare::save_to_project(&config, &project).unwrap();

        assert!(result.exists());
        assert!(result.to_string_lossy().contains(".polyfont"));
        assert!(result.to_string_lossy().contains("themes"));
        assert!(result.to_string_lossy().ends_with("fira-code.toml"));

        let content = std::fs::read_to_string(&result).unwrap();
        let parsed: PolyfontConfig = toml::from_str(&content).unwrap();
        assert_eq!(parsed.version, 1);
    }

    #[test]
    fn test_remote_registry_default() {
        let registry = RemoteThemeRegistry::default();
        assert!(!registry.themes.is_empty());
        assert!(registry.find("monaspace-dark").is_some());
        assert!(registry.find("nonexistent").is_none());
    }

    #[test]
    fn test_remote_registry_roundtrip() {
        let registry = RemoteThemeRegistry::default();
        let json = registry.to_json().unwrap();
        let parsed = RemoteThemeRegistry::from_json(&json).unwrap();
        assert_eq!(parsed.themes.len(), registry.themes.len());
        assert_eq!(parsed.list_names(), registry.list_names());
    }
}
